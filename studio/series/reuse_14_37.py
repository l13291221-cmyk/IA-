def to_img(ref):
    flip = ref.endswith("!")
    name = ref.strip("@!")
    return f"{name}_1.jpg" + (":flip" if flip else "")


def apply(plan, reuse):
    for n, m in reuse.items():
        sc = plan[str(n)]["scenes"]
        for i, ref in m.items():
            sc[i].pop("p", None)
            sc[i]["img"] = to_img(ref)


